using System.Net.Sockets;
using System.Text;

namespace TwinDesk.Core;

/// <summary>Generates the layout file understood by Deskflow 1.27's native core.</summary>
public static class ServerConfig
{
    public static string Generate(AppSettings settings)
    {
        ArgumentNullException.ThrowIfNull(settings);
        var errors = settings.Validate();
        if (errors.Count != 0) throw new ArgumentException(string.Join(Environment.NewLine, errors), nameof(settings));
        var text = new StringBuilder();
        text.AppendLine("# Generated by TwinDesk. Change settings in TwinDesk before starting the engine.");
        // Computer identities and server options live in the main INI in Deskflow 1.27.
        text.AppendLine("section: links");
        if (settings.EdgeSwitching)
        {
            var (outbound, inbound) = settings.Position switch
            {
                ScreenPosition.Left => ("left", "right"),
                ScreenPosition.Right => ("right", "left"),
                ScreenPosition.Above => ("up", "down"),
                ScreenPosition.Below => ("down", "up"),
                _ => throw new ArgumentOutOfRangeException(nameof(settings))
            };
            text.AppendLine($"    {settings.LocalName}:");
            text.AppendLine($"        {outbound} = {settings.PeerName}");
            text.AppendLine($"    {settings.PeerName}:");
            text.AppendLine($"        {inbound} = {settings.LocalName}");
        }
        text.AppendLine("end");
        text.AppendLine();
        text.AppendLine("section: options");
        if (settings.HotkeySwitching)
        {
            text.AppendLine($"    keystroke(Control+Alt+1) = switchToScreen({settings.LocalName})");
            text.AppendLine($"    keystroke(Control+Alt+2) = switchToScreen({settings.PeerName})");
        }
        // Always keep a way to return the physical keyboard and mouse to their own computer.
        text.AppendLine($"    keystroke(Control+Alt+Escape) = switchToScreen({settings.LocalName})");
        text.AppendLine("end");
        return text.ToString();
    }

    public static string FormatEndpoint(string host, int port)
    {
        if (port is < 1 or > 65535) throw new ArgumentOutOfRangeException(nameof(port));
        if (!AppSettings.IsHost(host)) throw new ArgumentException("无效的主机名或 IP 地址。", nameof(host));
        if (AppSettings.TryParseAddress(host, out var address))
            return address!.AddressFamily == AddressFamily.InterNetworkV6 ? $"[{address}]:{port}" : $"{address}:{port}";
        return $"{host}:{port}";
    }
}
